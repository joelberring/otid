import { db } from "../../../../../../lib/db";
import {
  importAdminLoginRoute,
  importAdminLogoutRoute,
  importAdminSessionStatusRoute
} from "../../../../../../lib/import-admin-route-handlers";

type Context = { params: Promise<{ raceId: string }> };

export async function GET(request: Request, { params }: Context): Promise<Response> {
  const { raceId } = await params;
  return importAdminSessionStatusRoute(db, request, raceId);
}

export async function POST(request: Request, { params }: Context): Promise<Response> {
  const { raceId } = await params;
  return importAdminLoginRoute(db, request, raceId);
}

export async function DELETE(request: Request, { params }: Context): Promise<Response> {
  const { raceId } = await params;
  return importAdminLogoutRoute(db, request, raceId);
}
