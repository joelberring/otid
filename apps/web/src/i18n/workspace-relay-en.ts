/** Engelska, arbetsytan del 9: stafetten (klasser, lag, lagkortet, start, avläsning och de publika listorna). */
type Point = "START" | "FINISH" | number;
const point = (value: Point) => value === "START" ? "start" : value === "FINISH" ? "finish" : String(value);
const pairs = (legs: readonly { from: Point; to: Point }[]) => legs.slice(0, 4).map(leg => `${point(leg.from)}–${point(leg.to)}`).join(", ") +
  (legs.length > 4 ? " and more" : "");
const ordinal = (n: number) => {
  const rest = n % 100;
  if (rest >= 11 && rest <= 13) return `${n}th`;
  return `${n}${["th", "st", "nd", "rd"][n % 10] ?? "th"}`;
};

