/** "3 h 20 min", "2 days 4 h" – a large clock deviation in whole minutes. */
function formatSkew(minutes: number): string {
  const total = Math.abs(minutes);
  const days = Math.floor(total / 1_440);
  const hours = Math.floor((total % 1_440) / 60);
  const rest = total % 60;
  return [days > 0 ? `${days} ${days === 1 ? "day" : "days"}` : "", hours > 0 ? `${hours} h` : "", rest > 0 && days === 0 ? `${rest} min` : ""]
    .filter(Boolean).join(" ") || "0 min";
}
const ordinal = (value: number) => ["first", "second", "third", "fourth", "fifth", "sixth", "seventh", "eighth", "ninth", "tenth"][value - 1]
  ?? `${value}th`;
const and = (values: readonly string[]) => values.length <= 1 ? values.join("") : `${values.slice(0, -1).join(", ")} and ${values.at(-1)}`;

